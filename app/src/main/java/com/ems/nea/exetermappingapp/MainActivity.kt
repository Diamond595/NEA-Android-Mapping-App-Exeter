    // Initialise the main and map settings view model to allow changes made to the settings datastore
    val mainSettingsViewModel: MainSettingsViewModel by viewModels { MainSettingsViewModel.Factory }
    val mapSettingsViewModel: MapSettingsViewModel by viewModels { MapSettingsViewModel.Factory }

    override fun onCreate(savedInstanceState: Bundle?) { // Autogenerated
        super.onCreate(savedInstanceState) // Autogenerated
        enableEdgeToEdge() // Autogenerated
        setContent { // Autogenerated
            // Get the current main and map settings from the datastore, with these initial values if it doesn't exist
            val mainSettings by mainSettingsViewModel.settingsFlow.collectAsStateWithLifecycle(
                initialValue = MainSettings(
                    darkTheme = isSystemInDarkTheme(),
                    textSizeMultiplier = 1f,
                    iconStyle = 0,
                    backgroundColour = MaterialTheme.colorScheme.background.toArgb(),
                    primaryColour = MaterialTheme.colorScheme.primary.toArgb(),
                    secondaryColour = MaterialTheme.colorScheme.secondary.toArgb()
                )
            )
            val mapSettings by mapSettingsViewModel.settingsFlow.collectAsStateWithLifecycle(
                initialValue = MapSettings(
                    buildingViewDistance = 1f,
                    roadNameViewDistance = 1f,
                    mainRoadColour = Color.argb(255, 255, 244, 79),
                    motorwayRoadColour = Color.argb(255, 0, 255, 0),
                    defaultRoadColour = Color.argb(255, 255, 255, 255),
                    buildingColour = Color.argb(255, 127, 127, 127),
                    parkColour = Color.argb(255, 144, 238, 144),
                    waterColour = Color.argb(255, 118, 203, 255),
                )
            )
            // Starts the UI rendering
            ExeterMappingAppTheme (
                // Sets the theme to the theme specified in the settings
                darkTheme = mainSettings.darkTheme
            ) {
                Surface() {
                    // Make a screen variable, that will update any UI components using it when it is updated
                    var screen by remember { mutableStateOf("home") }

                    // Layers the screens above the navigation bar
                    Column (
                        modifier = Modifier
                            // Fill the whole screen size
                            .fillMaxSize()
                            // Set the background to the colour specified in the settings
                            .background(
                                color = androidx.compose.ui.graphics.Color(mainSettings.backgroundColour),
                            )
                    ){
                        // Uses the weight to give the screen 9/10ths of the phone screen
                        Box(
                            modifier = Modifier
                                .weight(9f)
                        ) {
                            // Decides what screen to render based of the value of the screen variable
                            when (screen) {
                                "home" ->
                                    HomeScreen()

                                "test" ->
                                    SettingsTest(
                                        mainSettings,
                                        mapSettings
                                    )

                                "saved" ->
                                    SavedScreen()

                                "settings" ->
                                    SettingsScreen(
                                        mainSettings = mainSettings,
                                        mapSettings = mapSettings,
                                    )

                                // if the screen variable is not one of the above, it will render an error screen which just warns the user something is wrong
                                // should never be called
                                else ->
                                    ErrorScreen(
                                        screenName = screen
                                    )
                            }
                        }
                        // Uses the weight to give the navigation bar 1/10th of the phone screen
                        Box(
                            modifier = Modifier
                                .weight(1f)
                        ) {
                            // Calls the bottom navigation bar
                            BottomBar(
                                screen = screen, // Used to show selected screen
                                onScreenChange = { screen = it }, // When a button is clicked, the screen variable is set to what the button sets it as
                                mainSettings = mainSettings
                            )
                        }
                    }
                }
            }
        }
    }
